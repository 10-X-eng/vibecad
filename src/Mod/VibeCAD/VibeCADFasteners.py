class FastenerCatalogError(ValueError):
    """A direct catalog or standard-component validation failure."""


def _bounded_text(value: Any, *, name: str, maximum: int = 4096) -> str:
    text = str(value or "").strip()
    if not text:
        raise FastenerCatalogError(f"{name} must be non-empty.")
    if len(text) > maximum:
        raise FastenerCatalogError(
            f"{name} must contain at most {maximum} characters."
        )
    return text


def _catalog_search_terms(value: Any) -> tuple[str, ...]:
    return tuple(
        _CATALOG_SEARCH_TOKEN_RE.findall(str(value or "").casefold())
    )


def _catalog_search_rank(
    query: Any,
    row: Mapping[str, Any],
) -> tuple[int, ...] | None:
    """Rank generic partial matches without interpreting catalog semantics."""

    query_terms = _catalog_search_terms(query)
    if not query_terms:
        return ()
    fields = [
        str(row.get("standard") or "").casefold(),
        str(row.get("family") or "").casefold(),
        str(row.get("description") or "").casefold(),
        *[
            str(value).casefold()
            for value in row.get("nominal_threads", [])
        ],
    ]
    field_words = [
        _catalog_search_terms(field)
        for field in fields
    ]
    scores = []
    for term in query_terms:
        candidates = []
        for field, words in zip(fields, field_words):
            if term == field:
                candidates.append(0)
            elif term in words:
                candidates.append(1)
            elif field.startswith(term):
                candidates.append(2)
            elif any(word.startswith(term) for word in words):
                candidates.append(3)
            elif term in field:
                candidates.append(4)
        if not candidates:
            return None
        scores.append(min(candidates))
    return (sum(scores), *scores)


def _module_root() -> Path:
    return Path(__file__).resolve().parent


def _fasteners_root() -> Path:
    sibling = _module_root().parent / "Fasteners"
    if (sibling / "ScrewMaker.py").is_file():
        return sibling
    try:
        import FreeCAD as App

        installed = Path(str(App.getHomePath())) / "Mod" / "Fasteners"
        if (installed / "ScrewMaker.py").is_file():
            return installed
    except Exception:
        pass
    return sibling


def _load_provenance() -> dict[str, str]:
    global _PROVENANCE
    if _PROVENANCE is not None:
        return dict(_PROVENANCE)
    path = _module_root() / PROVENANCE_FILE
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise FastenerCatalogError(
            f"Bundled Fasteners provenance is unavailable at {path}: {exc}"
        ) from exc
    if not isinstance(value, Mapping) or set(value) != _PROVENANCE_FIELDS:
        raise FastenerCatalogError(
            "Bundled Fasteners provenance has an unsupported schema."
        )
    clean = {name: _bounded_text(value[name], name=name) for name in value}
    if not re.fullmatch(r"[0-9a-f]{40}", clean["revision"]):
        raise FastenerCatalogError(
            "Bundled Fasteners provenance has an invalid revision."
        )
    if clean["module"] != "Fasteners" or clean["license"] != "GPL-2.0-or-later":
        raise FastenerCatalogError(
            "Bundled Fasteners provenance changed its module or license identity."
        )
    _PROVENANCE = clean
    return dict(clean)


def provenance() -> dict[str, str]:
    """Return the exact source, revision, version, and license in this build."""

    return _load_provenance()


