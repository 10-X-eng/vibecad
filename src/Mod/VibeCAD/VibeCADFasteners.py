def _interface_frame(interface: Mapping[str, Any]) -> dict[str, list[float]]:
    kind = str(interface.get("kind") or "")
    if kind == "axis":
        position = list(interface.get("origin_mm") or [])
        direction = list(interface.get("direction") or [])
    elif kind == "plane":
        position = list(interface.get("origin_mm") or [])
        direction = list(interface.get("normal") or [])
    elif kind == "cylinder":
        position = list(interface.get("axis_origin_mm") or [])
        direction = list(interface.get("axis_direction") or [])
    else:
        raise FastenerCatalogError(
            f"Standard-component interface kind {kind!r} has no connector frame."
        )
    if len(position) != 3 or len(direction) != 3:
        raise FastenerCatalogError(
            f"Standard-component {kind} interface has malformed vectors."
        )
    def stable(value: Any, *, name: str) -> float:
        result = round(_finite_number(value, name=name), 12)
        return 0.0 if result == 0.0 else result

    clean_position = [
        stable(value, name="interface origin") for value in position
    ]
    clean_direction = [
        stable(value, name="interface direction") for value in direction
    ]
    magnitude = math.sqrt(sum(value * value for value in clean_direction))
    if magnitude <= 1.0e-12:
        raise FastenerCatalogError(
            f"Standard-component {kind} interface has a zero direction."
        )
    dx, dy, dz = (value / magnitude for value in clean_direction)
    # Shortest quaternion rotating the component-local +Z axis onto the
    # published engineering direction. The antiparallel case is an exact
    # half-turn about +X.
    if dz <= -1.0 + 1.0e-12:
        rotation = [1.0, 0.0, 0.0, 0.0]
    else:
        rotation = [-dy, dx, 0.0, 1.0 + dz]
        quaternion_magnitude = math.sqrt(
            sum(value * value for value in rotation)
        )
        rotation = [
            stable(
                value / quaternion_magnitude,
                name="interface rotation",
            )
            for value in rotation
        ]
    return {
        "position": clean_position,
        "rotation": rotation,
    }


def fastener_bom_properties(
    identity: Mapping[str, Any],
) -> list[dict[str, Any]]:
    """Return the stable scalar properties consumed by native Assembly BOM."""

    values = (
        ("PartNumber", str(identity.get("part_number") or "")),
        ("Description", str(identity.get("description") or "")),
        (PROP_STANDARD, str(identity.get("standard") or "")),
        (PROP_FAMILY, str(identity.get("family") or "")),
        (PROP_NOMINAL_SIZE, str(identity.get("nominal_size") or "")),
        (PROP_CATALOG_PART_NUMBER, str(identity.get("part_number") or "")),
        (PROP_CANONICAL_KEY, str(identity.get("canonical_key") or "")),
    )
    result: list[dict[str, Any]] = []
    for name, value in values:
        if not value:
            raise FastenerCatalogError(
                f"Fastener BOM identity is missing {name}."
            )
        result.append(
            {
                "name": name,
                "property_type": "App::PropertyString",
                "kind": "string",
                "value": value,
            }
        )
    return result


def assembly_component_contract(
    shape: Any,
    identity: Mapping[str, Any],
) -> dict[str, Any]:
    """Describe one generated fastener as an Assembly source.

    This contract is derived from the exact generated BREP and canonical
    catalog identity in both the isolated worker and the host validator.
    """

    if str(identity.get("schema") or "") != COMPONENT_SCHEMA:
        raise FastenerCatalogError(
            "Assembly fastener identity has an unsupported component schema."
        )
    if shape is None or bool(shape.isNull()) or not bool(shape.isValid()):
        raise FastenerCatalogError(
            "Assembly fastener source must contain one valid generated BREP."
        )
    if len(shape.Solids) != 1:
        raise FastenerCatalogError(
            "Assembly fastener source must contain exactly one solid."
        )
    proxy = type("_FastenerShape", (), {"Shape": shape})()
    native_interfaces = _interfaces(
        proxy,
        str(identity["family"]),
        float(identity["nominal_diameter_mm"]),
        standard=str(identity["standard"]),
        length_mm=(
            float(identity["length_mm"])
            if identity.get("length_mm") is not None
            else None
        ),
    )
    published: dict[str, dict[str, Any]] = {}
    geometry_types = {
        "axis": "line",
        "plane": "plane",
        "cylinder": "cylinder",
    }
    for name, raw in dict(native_interfaces["interfaces"]).items():
        interface = dict(raw)
        kind = str(interface.get("kind") or "")
        geometry_type = geometry_types.get(kind)
        if geometry_type is None:
            continue
        published[name] = {
            "model_id": str(identity["canonical_key"]),
            "publication_name": name,
            "output_key": str(identity["canonical_key"]),
            "subelements": [],
            "geometry": [{"geometry_type": geometry_type}],
            "standard_frame": _interface_frame(interface),
        }
    if not {"axis", "thread_axis", "mounting_plane"} <= set(published):
        raise FastenerCatalogError(
            "Generated fastener is missing its required Assembly interfaces."
        )
    return {
        "label": str(identity["part_number"]),
        "type_id": "Part::FeaturePython",
        "source_kind": "standard_fastener",
        "transient_topology": True,
        # Catalog fasteners have a canonical local frame, so their component
        # origin is stable across regeneration and is safe for Assembly joints.
        # Their generated FaceN/EdgeN names remain transient and are still
        # rejected by the transient_topology guard in the Assembly worker.
        "requires_semantic_interfaces": False,
        "published_interfaces": published,
        "facts": {
            "shape_type": str(shape.ShapeType),
            "solids": len(shape.Solids),
            "shells": len(shape.Shells),
            "faces": len(shape.Faces),
            "wires": len(shape.Wires),
            "edges": len(shape.Edges),
            "vertices": len(shape.Vertexes),
        },
        "document_file_name": "",
        "bom_properties": fastener_bom_properties(identity),
    }


def _identity_from_object(obj: Any) -> dict[str, Any]:
    standard = canonical_standard(getattr(obj, "Type", ""))
    nominal_size = _catalog_token(
        getattr(obj, "Diameter", ""),
        _nominal_sizes(standard),
        name="Diameter",
    )
    options: dict[str, Any] = {}
    parameters = _standard_parameters(standard)
    for name, (requirement, property_name, kind) in _OPTION_PROPERTIES.items():
        if requirement not in parameters or not hasattr(obj, property_name):
            continue
        value = getattr(obj, property_name)
        if kind == "length":
            options[name] = float(value.Value)
        elif kind == "integer":
            options[name] = int(value)
        elif kind == "boolean":
            options[name] = bool(value)
        else:
            options[name] = str(value)
    return resolve_fastener(
        standard=standard,
        nominal_thread=nominal_size,
        length_mm=_active_length(obj),
        model_thread=bool(getattr(obj, "Thread", False)),
        left_handed=bool(getattr(obj, "LeftHanded", False)),
        options=options,
    )


def fastener_feature_identity(obj: Any) -> dict[str, Any]:
    """Return and verify the current catalog identity of a native feature."""

    if str(getattr(obj, PROP_SCHEMA, "") or "") != COMPONENT_SCHEMA:
        raise FastenerCatalogError(
            "object is not a VibeCAD standard-fastener feature."
        )
    identity = _identity_from_object(obj)
    stored_key = str(getattr(obj, PROP_CANONICAL_KEY, "") or "")
    if stored_key and stored_key != identity["canonical_key"]:
        raise FastenerCatalogError(
            "The fastener's editable parameters do not match its stored "
            "canonical identity; recompute the object before editing it."
        )
    return identity


def compatible_fastener_standards(obj: Any) -> list[str]:
    """List standards that can safely reuse this feature's native properties."""

    identity = fastener_feature_identity(obj)
    modules = _load_upstream()
    parameter_group = modules["FastenersCmd"].FSGetParams(identity["standard"])
    compatible = {
        str(standard)
        for standard in modules["ScrewMaker"].screwTables
        if modules["FastenersCmd"].FSGetParams(str(standard)) is parameter_group
    }
    compatible.add(str(identity["standard"]))
    return sorted(compatible)


def update_fastener_feature(
    obj: Any,
    *,
    standard: Any,
    nominal_thread: Any,
    length_mm: Any = None,
    model_thread: bool = False,
    left_handed: bool = False,
    options: Mapping[str, Any] | None = None,
    label: str | None = None,
) -> dict[str, Any]:
    """Update one native feature without replacing its document identity.

    Standards may change only within the upstream generator's compatible
    property group. A caller that needs a different family must insert a new
    component, which avoids silently changing references to another kind of
    hardware.
    """

    current = fastener_feature_identity(obj)
    previous_label = str(getattr(obj, "Label", "") or "")
    identity = resolve_fastener(
        standard=standard,
        nominal_thread=nominal_thread,
        length_mm=length_mm,
        model_thread=model_thread,
        left_handed=left_handed,
        options=options,
    )
    compatible = compatible_fastener_standards(obj)
    if identity["standard"] not in compatible:
        raise FastenerCatalogError(
            f"standard {identity['standard']!r} cannot replace "
            f"{current['standard']!r} in place because their native parameter "
            "contracts differ. Insert a new standard component instead. "
            f"Compatible standards: {compatible}."
        )
    proxy = getattr(obj, "Proxy", None)
    if not isinstance(proxy, VibeCADFastenerProxy):
        raise FastenerCatalogError(
            "object has no VibeCAD standard-fastener parametric proxy."
        )
    delegate = proxy._restore_delegate(obj)
    # The upstream generator caches its last-seen property values on the
    # Python proxy, but those Python fields are not part of FreeCAD's undo
    # journal. Rebase that cache from the exact live feature before applying
    # this controlled edit; otherwise an edit after Undo can compare against
    # future values and incorrectly enter its custom-length path.
    delegate.BackupObject(obj)
    if str(obj.Type) != str(identity["standard"]):
        obj.Type = compatible
        obj.Type = str(identity["standard"])
        delegate.VerifyMissingAttrs(obj, str(identity["standard"]))
        obj.Proxy = proxy
    diameter_values = list(_nominal_sizes(str(identity["standard"])))
    obj.Diameter = diameter_values
    obj.Diameter = str(identity["nominal_size"])
    for option_name, option_value in dict(identity["options"]).items():
        _set_object_option(obj, option_name, option_value)
    if identity["length_mm"] is not None:
        if isinstance(obj.Length, str):
            obj.Length = list(identity["allowed_length_tokens"])
            obj.Length = str(identity["length_token"])
        else:
            obj.Length = float(identity["length_mm"])
    if hasattr(obj, "LeftHanded"):
        obj.LeftHanded = bool(identity["left_handed"])
    if hasattr(obj, "Thread"):
        obj.Thread = bool(identity["model_thread"])
    proxy.standard = str(identity["standard"])
    obj.Document.recompute()
    observed = _identity_from_object(obj)
    if observed["canonical_key"] != identity["canonical_key"]:
        raise FastenerCatalogError(
            "The pinned generator changed the requested catalog identity "
            "during the in-place update."
        )
    _write_metadata(obj, observed)
    if label is not None:
        obj.Label = (
            _bounded_text(label, name="label")
            if str(label).strip()
            else str(observed["part_number"])
        )
    elif previous_label == str(current["part_number"]):
        obj.Label = str(observed["part_number"])
    return observed


